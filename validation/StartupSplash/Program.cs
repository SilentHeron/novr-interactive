using NOVR.VrUi.Native;
var checks = 0;
void Check(bool ok, string message) { if (!ok) throw new Exception(message); Console.WriteLine("PASS " + message); checks++; }
Check(!StartupSplashState.IsMultiplayerSession(false, false, true, false), "inactive default-listening manager is not multiplayer");
Check(!StartupSplashState.IsMultiplayerSession(false, true, false, true), "active offline loader host is not multiplayer");
Check(!StartupSplashState.IsMultiplayerSession(false, false, false, true), "offline local client stopping after host is not multiplayer");
Check(StartupSplashState.IsMultiplayerSession(false, true, true, true), "active listening host is multiplayer");
Check(StartupSplashState.IsMultiplayerSession(false, false, true, true), "remote client connection is multiplayer");
Check(StartupSplashState.IsMultiplayerSession(true, false, false, false), "explicit multiplayer mode excludes startup even before connection");
var stock = new StartupSplashState();
Check(!stock.Update(MissionContentPhase.Ready, true, false, false), "stock startup has no invented loading screen");
Check(!stock.Finished, "early ready does not prematurely close observation before loader registration");
Check(stock.Update(MissionContentPhase.Preparing, true, false, false), "observed loader hides menu during preparation");
for (var i = 0; i < 10000; i++) stock.Update(MissionContentPhase.Preparing, true, false, false);
Check(stock.Visible, "frame count cannot authorize completion");
Check(!stock.CanQuit, "loading entry cannot directly quit");
stock.ToggleExit(); Check(stock.CanQuit, "explicit exit confirmation enables quit");
stock.CancelExit(); Check(!stock.CanQuit && stock.Visible, "canceling exit returns to loading without dismissing gate");
stock.ToggleExit();
Check(!stock.Update(MissionContentPhase.Ready, true, false, false), "actual completion reveals menu");
Check(stock.Finished && !stock.CanQuit && !stock.ExitConfirmation, "completion clears pending exit confirmation");
Check(!stock.Update(MissionContentPhase.Failed, true, false, false), "startup splash cannot reappear later after completion");
var content = new MissionContentState(); var gate = new StartupSplashState();
content.Begin(); Check(gate.Update(content.Phase, true, false, false), "coroutine start shows splash");
content.ObserveSuccess(); Check(gate.Update(content.Phase, true, false, false), "success message alone does not reveal the menu");
content.End(true); Check(!gate.Update(content.Phase, true, false, false), "normal end plus success reveals menu");
var failure = new StartupSplashState();
Check(failure.Update(MissionContentPhase.Failed, true, false, false) && failure.Failed, "observed loader failure stays explicit");
failure.ToggleExit(); Check(failure.CanQuit, "failed loader still permits deliberate exit");
failure.CancelExit(); Check(failure.Visible && !failure.CanQuit, "failed loader back action remains safe");
var unverified = new StartupSplashState();
Check(!unverified.Update(MissionContentPhase.Unverified, true, false, false) && unverified.Finished, "unknown or late loader cannot trap menu behind splash");
var flight = new StartupSplashState();
Check(!flight.Update(MissionContentPhase.Preparing, true, true, false) && flight.Finished, "actual aircraft suppresses splash permanently");
var multiplayer = new StartupSplashState();
Check(!multiplayer.Update(MissionContentPhase.Preparing, true, false, true) && multiplayer.Finished, "multiplayer suppresses splash permanently");
var vr = new StartupSplashState();
Check(!vr.Update(MissionContentPhase.Preparing, false, false, false) && !vr.Finished, "desktop mode never gets VR startup camera");
Check(vr.Update(MissionContentPhase.Preparing, true, false, false), "entering VR during loading restores readable splash");
Check(vr.Update(MissionContentPhase.Preparing, true, false, false), "offline temporary scene with no pilot remains loading");
Console.WriteLine($"{checks} startup splash lifecycle checks passed.");
