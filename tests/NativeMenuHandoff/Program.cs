using NOVR.VrUi.Native;
using UnityEngine;
using NuclearOption.MissionEditorScripts;
using NuclearOption.SavedMission;
var passed = 0;
void Check(bool value) { if (!value) throw new Exception("Menu assertion failed at " + passed); passed++; }
var canvas = new GameObject();
var holder = new GameObject { activeSelf = false, Parent = canvas };
var customize = new CustomizeMissionMenu(holder);
canvas.Components.Add(customize);
var editor = new FileMenu();
editor.gameObject.Parent = canvas;
editor.gameObject.activeSelf = false;
canvas.Components.Add(editor);
var handoff = new NativeStockMenuHandoff();
Check(!handoff.IsVisible(canvas));
holder.activeSelf = true;
Check(handoff.IsVisible(canvas));
holder.activeSelf = false;
Check(!handoff.IsVisible(canvas));
editor.gameObject.activeSelf = true;
Check(handoff.IsVisible(canvas));
canvas.activeSelf = false;
Check(!handoff.IsVisible(canvas));
canvas.activeSelf = true;
Check(handoff.IsVisible(canvas));
Check(!handoff.IsVisible(null));
Check(handoff.IsVisible(canvas));
var otherScene = new GameObject();
Check(!handoff.IsVisible(otherScene));
Check(handoff.IsVisible(canvas));

var select = new MissionSelectPanel();
var picker = new MissionPicker(select);
var first = new MissionKey("Domination");
var second = new MissionKey("Confrontation");
NativeMissionSelection.Select(picker, first);
Check(picker.Loads == 1 && select.SelectedMission == first);
picker.Mission!.Description = "Customized";
var edited = picker.Mission;
NativeMissionSelection.Select(picker, first);
Check(picker.Loads == 1 && ReferenceEquals(edited, picker.Mission));
Check(NativeMissionSelection.TryGet(picker, first, out var current) && ReferenceEquals(current, edited));
Check(!NativeMissionSelection.TryGet(picker, second, out current) && current == null);
NativeMissionSelection.Select(picker, second);
Check(picker.Loads == 2 && select.SelectedMission == second && picker.Mission!.Description == "");
picker.Mission = null;
NativeMissionSelection.Select(picker, second);
Check(picker.Loads == 3 && picker.Mission != null);
var fallback = new MissionPicker(null);
NativeMissionSelection.Select(fallback, first);
Check(fallback.Loads == 1);
Check(!NativeMissionSelection.TryGet(fallback, first, out _));
passed += CanvasDiscoveryChecks.Run();
passed += CaptureLifetimeChecks.Run();
passed += PanelVisibilityChecks.Run();
passed += MenuAvailabilityChecks.Run();
passed += MultiplayerSelectionChecks.Run();
passed += await MultiplayerHostingChecks.Run();
passed += await SinglePlayerLaunchChecks.Run();
passed += SinglePlayerSelectionChecks.Run();
Console.WriteLine($"{passed} source-linked menu handoff/selection/discovery/capture assertions passed (native UI doubles; no renderer/game launch).");
